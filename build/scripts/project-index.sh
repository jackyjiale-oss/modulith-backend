# check_map: the MAP.md rules; prints one line per problem and returns 1 when there is any.
check_map() {
  local map="$out/MAP.md" problem=0 token name line text="" bt='`' pattern checked=" "
  local lines=()
  if [[ ! -f "$map" ]]; then
    echo "project-index: MAP.md is missing in $out" >&2
    return 1
  fi
  pattern="$bt([^$bt]+)$bt"
  mapfile -t lines < "$map"
  # Every backticked repository path must exist. A token with a space, a brace, a star, an angle bracket or an ellipsis is a pattern
  # or a placeholder, not a path. Bash builtins only (no process per line); a CR at the end of a line is dropped.
  for line in "${lines[@]}"; do
    line="${line%$'\r'}"
    text+="$line"$'\n'
    while [[ "$line" =~ $pattern ]]; do
      token="${BASH_REMATCH[1]}"
      line="${line#*"${BASH_REMATCH[0]}"}"
      case "$token" in
        src/* | tests/* | build/* | docs/* | .github/*) ;;
        *) continue ;;
      esac
      case "$token" in
        *" "* | *"{"* | *"*"* | *"<"* | *"..."*) continue ;;
      esac
      [[ "$checked" == *" $token "* ]] && continue
      checked+="$token "
      if [[ ! -e "$root/$token" ]]; then
        echo "project-index: MAP.md names a path that does not exist: $token" >&2
        problem=1
      fi
    done
  done
  for name in $shards; do
    if [[ "$text" != *"$name.md"* ]]; then
      echo "project-index: MAP.md does not name the shard file: $name.md" >&2
      problem=1
    fi
  done
  if (( ${#lines[@]} > 120 )); then
    echo "project-index: MAP.md has ${#lines[@]} lines, at most 120 are allowed" >&2
    problem=1
  fi
  return "$problem"
}

# check_mode: generates into a temporary directory and compares it with --out, then checks MAP.md.
check_mode() {
  local name file base known status=0
  shard_dir="$work/generated"
  generate
  for name in $shards; do
    if [[ ! -f "$out/$name.md" ]]; then
      echo "project-index: missing: $name" >&2
      status=1
    elif ! cmp -s "$shard_dir/$name.md" "$out/$name.md"; then
      echo "project-index: stale: $name" >&2
      status=1
    fi
  done
  for file in "$out"/*.md; do
    [[ -e "$file" ]] || continue
    base="${file##*/}"
    [[ "$base" == "MAP.md" ]] && continue
    known=0
    for name in $shards; do
      if [[ "$base" == "$name.md" ]]; then known=1; fi
    done
    if (( known == 0 )); then
      echo "project-index: unknown shard: $base" >&2
      status=1
    fi
  done
  check_map || status=1
  if (( status != 0 )); then
    echo "project-index: fix the cause, then regenerate with: bash build/scripts/project-index.sh (a conflict in a shard is regenerated, never merged by hand)" >&2
  fi
  return "$status"
}

main() {
  local mode="write" script_dir
  script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
  while (( $# > 0 )); do
    case "$1" in
      --check) mode="check"; shift ;;
      --root)
        (( $# >= 2 )) && [[ "$2" != --* ]] || fail "--root needs a directory"
        root="$2"; shift 2 ;;
      --out)
        (( $# >= 2 )) && [[ "$2" != --* ]] || fail "--out needs a directory"
        out="$2"; shift 2 ;;
      *) fail "unknown argument: $1 (usage: project-index.sh [--check] [--root DIR] [--out DIR])" ;;
    esac
  done
  [[ -n "$root" ]] || root="$script_dir/../.."
  [[ -d "$root" ]] || fail "not a directory: $root"
  # --out may be relative to where the script was started, and may not exist yet: make it absolute before changing directory.
  if [[ -z "$out" ]]; then
    out="$root/docs/superpowers/index"
  fi
  case "$out" in
    /* | [A-Za-z]:*) ;;
    *) out="$PWD/$out" ;;
  esac
  root="$(cd "$root" && pwd)"
  cd "$root"
  work="$(mktemp -d)"
  trap 'rm -rf "$work"' EXIT
  prepare_files
  if [[ "$mode" == "check" ]]; then
    check_mode
  else
    # Atomic: a parse error on any shard leaves --out as it was.
    shard_dir="$work/generated"
    generate
    mkdir -p "$out"
    cp "$shard_dir"/*.md "$out"/
  fi
}

# Run main only when executed; the tests source this file to call need_rows, check_map, main and the shard functions.
if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
  main "$@"
fi
