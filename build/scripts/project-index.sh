#!/usr/bin/env bash
# Generates the project index (project index design): eight shards under docs/superpowers/index/ that list routes, permissions, error
# codes, events, jobs, configuration, tests and template switch markers, so that none of them has to be found with a wide search.
# It reads the tree it is run in and hard-codes no module name. MAP.md in the same directory is hand-written; --check keeps it honest.
#
# Usage: bash build/scripts/project-index.sh [--check] [--root DIR] [--out DIR]
#   no argument  rewrite every shard in --out
#   --check      rewrite nothing: generate into a temporary directory with the same code, compare it byte for byte with --out and check
#                MAP.md (it exists, every repository path it names exists, it names every shard, at most 120 lines)
#   --root DIR   the tree to read (default: two levels above this script)
#   --out DIR    where the shards and MAP.md are (default: <root>/docs/superpowers/index)
# Output: shards are deterministic (LC_ALL=C, LF, no timestamps), so --check gives the same answer on Windows and on Linux.
# Exit: 0 ok, 1 --check found a stale or missing shard, an unknown shard file or a MAP.md problem, 2 usage or parse error (a source that
# yields zero rows although the tree has some is a parse error, never an empty table).
#
# For the functions below that print rows (emit_<shard>): one record per line, fields separated by "|" in the column order of the shard,
# unsorted; a literal "|" inside a field is written "\|". write_shard sorts the rows and renders the table.
set -euo pipefail

export LC_ALL=C

fail() { echo "project-index: $*" >&2; exit 2; }
fail_parse() { fail "$*"; }

# The shard names, in the order MAP.md must list them; each is a file <name>.md.
shards="routes permissions errors events jobs config tests markers"

banner='<!-- Generated by build/scripts/project-index.sh; do not edit. Regenerate with: bash build/scripts/project-index.sh -->'

# The whole-line marker rule of template-smoke.sh (a line that only quotes a marker inline is prose, not a marker), with the slash
# escapes removed: "\/" means "/" but makes GNU grep 3.8 and newer warn about a stray backslash; the lines matched are the same.
marker_line='^[[:space:]]*(//|<!--|%%)?#(if|elseif|else|endif)([[:space:]]|\(|-->|$)'

# Set by main: root, out (absolute), work (a temporary directory), shard_dir (where generate writes) and files_cache.
root="" out="" work="" shard_dir="" files_cache=""

# prepare_files: lists the files of the tree once, relative to the root and sorted, into files_cache. With a .git (a directory, or a file
# in a git worktree) the list is git ls-files (tracked files only, minus the ones deleted from the working copy); else find, which
# skips bin, obj and .git.
prepare_files() {
  files_cache="$work/files.txt"
  if [[ -e "$root/.git" ]]; then
    git -C "$root" ls-files -z > "$work/ls.z" || fail_parse "git ls-files failed in $root"
    git -C "$root" ls-files -z --deleted > "$work/deleted.z" || fail_parse "git ls-files --deleted failed in $root"
    tr '\0' '\n' < "$work/ls.z" | sort -u > "$work/tracked.txt"
    tr '\0' '\n' < "$work/deleted.z" | sort -u > "$work/deleted.txt"
    comm -23 "$work/tracked.txt" "$work/deleted.txt" > "$files_cache"
  else
    (cd "$root" && find . -type f -not -path '*/bin/*' -not -path '*/obj/*' -not -path '*/.git/*' -print) \
      | sed 's|^\./||' | sort -u > "$files_cache"
  fi
}

# list_files: the relative paths of the tree, sorted, one per line.
list_files() {
  cat "$files_cache"
}

# need_rows <shard> <count> [sources]: a parse error (exit 2) when a shard has no rows although the tree has sources for it. sources is
# the number of source files found and must be numeric (default 1: the caller only asks when it found some).
need_rows() {
  local shard="$1" count="$2" sources="${3-1}"
  if (( sources > 0 && count == 0 )); then
    fail_parse "$shard: no rows although the tree has $sources source file(s) for it; the parser does not know their shape"
  fi
}

# render_rows: turns "|"-separated records on stdin into pipe-table rows ("\|" stays a literal pipe inside a cell).
render_rows() {
  sed -E -e 's/\\\|/\x01/g' -e 's/\|/ | /g' -e 's/\x01/\\|/g' -e 's/^/| /' -e 's/$/ |/'
}

# A shard file is built in three steps, with Bash builtins for all but the sort of the rows (a process costs a lot on Windows):
#   shard_begin <name> <title>
#   shard_table <heading> <note> <header-row> <rows-file>   (once for each table, in order)
#   shard_end
# writes <shard_dir>/<name>.md: the banner, "# title", "Rows: N", then the tables. "Rows: N" is the TOTAL number of data rows over all the
# tables of the shard. A table is its optional "## heading" line, its optional free-text note line, the header row, the separator and the
# rows sorted with LC_ALL=C; tables are separated by one blank line. The header row is "|"-separated like a record (see the top of this
# file); the rows are rendered, then sorted. An empty heading or note is left out, and an empty rows file needs no sort.
shard_name="" shard_title="" shard_body="" shard_rows=0 shard_tables=0
shard_begin() {
  shard_name="$1" shard_title="$2" shard_body="" shard_rows=0 shard_tables=0
}

shard_table() {
  local heading="$1" note="$2" header="$3" rows_file="$4"
  local sorted="$work/$shard_name.$shard_tables.sorted" lines=() columns=() separator="|" piece i
  if [[ -s "$rows_file" ]]; then
    render_rows < "$rows_file" | sort > "$sorted"
    mapfile -t lines < "$sorted"
  fi
  IFS='|' read -r -a columns <<< "$header"
  for i in "${columns[@]}"; do separator+=" --- |"; done
  if (( shard_tables > 0 )); then shard_body+=$'\n'; fi
  if [[ -n "$heading" ]]; then
    printf -v piece '## %s\n\n' "$heading"
    shard_body+="$piece"
  fi
  if [[ -n "$note" ]]; then
    printf -v piece '%s\n\n' "$note"
    shard_body+="$piece"
  fi
  printf -v piece '| %s |\n%s\n' "${header//|/ | }" "$separator"
  shard_body+="$piece"
  if (( ${#lines[@]} > 0 )); then
    printf -v piece '%s\n' "${lines[@]}"
    shard_body+="$piece"
  fi
  shard_rows=$((shard_rows + ${#lines[@]}))
  shard_tables=$((shard_tables + 1))
}

shard_end() {
  printf '%s\n\n# %s\n\nRows: %s\n\n%s' "$banner" "$shard_title" "$shard_rows" "$shard_body" > "$shard_dir/$shard_name.md"
}

# write_shard <name> <title> <header-row> <rows-file>: a shard with one table and no heading.
write_shard() {
  shard_begin "$1" "$2"
  shard_table "" "" "$3" "$4"
  shard_end
}

# shard_meta <name>: sets the title and the tables of a shard: title_text; heading1 and header_text (the "|"-separated column names of
# table 1); heading2 and header2_text (table 2, empty when the shard has one table). No subshell: a fork costs a lot on Windows.
# A shard with two tables has emit_<name> (rows of table 1) and emit_<name>_2 (rows of table 2); the latter may set table_note, the line
# printed under the heading of table 2 (reset to empty before each call).
title_text="" heading1="" header_text="" heading2="" header2_text="" table_note=""
shard_meta() {
  heading1="" heading2="" header2_text=""
  case "$1" in
    routes) title_text="Routes"; header_text="module|method|route|handler|permission|file" ;;
    permissions) title_text="Permissions"; header_text="code|module|admin default|file" ;;
    errors)
      title_text="Error codes"
      heading1="Declared codes"; header_text="code|module|http|resource key|file"
      heading2="Resource-only keys"; header2_text="key|http|resx file" ;;
    events) title_text="Integration events"; header_text="event|publisher|handlers" ;;
    jobs) title_text="Recurring jobs"; header_text="job|module|config keys|file" ;;
    config) title_text="Configuration sections"; header_text="section|owner|documented in" ;;
    tests)
      title_text="Tests"
      heading1="Folders"; header_text="test project|folder|source area|files"
      heading2="Name pairs"; header2_text="source|test" ;;
    markers) title_text="Template switch markers"; header_text="file|kinds|expressions" ;;
    *) fail "no title or header for shard $1" ;;
  esac
}

# The shards below are stubs here (a table with no rows); later tasks give each its parser.
emit_events() { :; }
emit_jobs() { :; }
emit_config() { :; }
emit_tests() { :; }
emit_tests_2() { :; }

# routes_awk: one awk run over the tracked file list (stdin, from files_cache) that reads the C# files it needs with getline. Three kinds:
#   E  src/Modules/<Module>/<Project>/.../Endpoints/*Endpoints.cs   the routes; only these give rows
#   M  src/Modules/<Module>/<Project>/*Module.cs                    module extensions that call the endpoint extensions
#   P  src/Host/<Project>/Program.cs                                the host: `var api = app.MapGroup("/api/v1"); api.MapXEndpoints();`
# Pass 1 (scan_file) reads each file line by line (CR and // comments removed) and records, per scope (a file and the Map...Endpoints
# extension being read, any other method, or the top level of the file): `var X = Y.MapGroup("p")` (group X under Y),
# `X.MapFooEndpoints()` calls (Foo takes the prefix of X in the caller's scope), `MapFooEndpoints(this T P)` declarations (P is the
# caller's group), `const string N = "v"`, the first generic argument of the ICommandHandler<...> or IQueryHandler<...> parameter of
# each method, and each statement (from a line with `.Map` to the line with `;`) holding `X.Map(Get|Post|Put|Patch|Delete)(route,
# Method)` with its chained RequirePermission(P) / AllowAnonymous() / RequireAuthorization() (authenticated) / RequireAuthorization("N")
# (the policy N). Pass 2 (END) resolves each route's prefix through the group and caller chain (only the top level of Program.cs is the
# root, where `app` lives) and prints module|METHOD|route|handler|permission|file.
# Errors (exit 3, the message in errfile), so that no shape gives a wrong row: an endpoint file with MapGroup or a Map...Endpoints call
# but zero routes; any other .MapX call in an endpoint file; an extension called from two places or declared in two files; a prefix that
# cannot be resolved (an extension not named Map...Endpoints or not on one line, a helper method); a route with no authorization call of
# its own (group-level authorization is not read); a file that cannot be read.
# shellcheck disable=SC2016
routes_awk='
function strip_comment(s,   k, c, n, inq) {
  if (index(s, "//") == 0) return s
  inq = 0; n = length(s)
  for (k = 1; k <= n; k++) {
    c = substr(s, k, 1)
    if (inq && c == "\\") { k++; continue }
    if (c == "\"") inq = !inq
    else if (!inq && c == "/" && substr(s, k + 1, 1) == "/") return substr(s, 1, k - 1)
  }
  return s
}
function first_generic(s,   k, c, depth, out) {
  depth = 0; out = ""
  for (k = 1; k <= length(s); k++) {
    c = substr(s, k, 1)
    if (c == "<") depth++
    else if (c == ">") { if (depth == 0) break; depth-- }
    else if (c == "," && depth == 0) break
    out = out c
  }
  gsub(/[ \t]/, "", out)
  return out
}
function join(a, b,   r) {
  sub(/^\/+/, "", b)
  r = (b == "" ? a : a "/" b)
  gsub(/\/\/+/, "/", r)
  if (r != "/") sub(/\/$/, "", r)
  return r
}
function unknown(i, what) {
  if (!(i in unknown_at)) unknown_at[i] = what " at line " lineno
}
# process: one statement of file i in scope sc; each .MapX occurrence is handled at its position.
function process(i, sc, stmt,   rest, before, after, tok, name, recv, x, arg, meth, perm, p, key) {
  rest = stmt
  while (match(rest, /\.Map[A-Za-z0-9_]*[(<]/)) {
    before = substr(rest, 1, RSTART - 1); tok = substr(rest, RSTART, RLENGTH); after = substr(rest, RSTART + RLENGTH)
    rest = after
    name = substr(tok, 5, length(tok) - 5)
    recv = ""
    if (match(before, /[A-Za-z_][A-Za-z0-9_]*[ \t]*$/)) { recv = substr(before, RSTART, RLENGTH); sub(/[ \t]+$/, "", recv); before = substr(before, 1, RSTART - 1) }
    if (name == "Group" && substr(tok, length(tok)) == "(") {
      if (recv != "" && match(after, /^[ \t]*"[^"]*"[ \t]*\)/) && match(before, /[A-Za-z_][A-Za-z0-9_]*[ \t]*=[ \t]*$/)) {
        x = substr(before, RSTART, RLENGTH); sub(/[ \t]*=[ \t]*$/, "", x)
        match(after, /"[^"]*"/); p = substr(after, RSTART + 1, RLENGTH - 2)
        key = sc SUBSEP x
        gpar[key] = recv; gpath[key] = p
        if (fkind[i] == "E") groups[i]++
      } else if (fkind[i] == "E") unknown(i, ".MapGroup without `var X = Y.MapGroup(\"literal\")`")
    } else if (name ~ /Endpoints$/ && substr(tok, length(tok)) == "(") {
      if (recv == "") { if (fkind[i] == "E") unknown(i, ".Map" name " without a receiver"); continue }
      if (fkind[i] == "E") groups[i]++
      if (!(("Map" name) in caller_var)) { caller_scope["Map" name] = sc; caller_var["Map" name] = recv }
      else if (caller_scope["Map" name] != sc || caller_var["Map" name] != recv) fail("routes: extension Map" name " called from two places in " fname[i])
    } else if (name ~ /^(Get|Post|Put|Patch|Delete)$/ && substr(tok, length(tok)) == "(") {
      if (fkind[i] != "E") continue
      if (recv == "" || !match(after, /^[ \t]*("[^"]*"|[A-Za-z_][A-Za-z0-9_.]*)[ \t]*,[ \t]*[A-Za-z_][A-Za-z0-9_]*[ \t]*\)/)) {
        unknown(i, ".Map" name " whose arguments are not (route, Method)"); continue
      }
      arg = substr(after, RSTART, RLENGTH)
      meth = arg; sub(/^.*,[ \t]*/, "", meth); sub(/[ \t]*\)$/, "", meth)
      match(arg, /^[ \t]*("[^"]*"|[A-Za-z_][A-Za-z0-9_.]*)/); arg = substr(arg, RSTART, RLENGTH); sub(/^[ \t]+/, "", arg)
      perm = "-"
      if (match(after, /RequirePermission\([^)]*\)/)) { perm = substr(after, RSTART + 18, RLENGTH - 19); gsub(/[ \t]/, "", perm) }
      else if (after ~ /AllowAnonymous\([ \t]*\)/) perm = "anonymous"
      else if (match(after, /RequireAuthorization\([^)]*\)/)) {
        perm = substr(after, RSTART + 21, RLENGTH - 22); gsub(/[ \t"]/, "", perm)
        if (perm == "") perm = "authenticated"
      }
      nr++; rfile[nr] = i; rscope[nr] = sc; rvar[nr] = recv; rverb[nr] = toupper(name); rarg[nr] = arg; rmeth[nr] = meth; rperm[nr] = perm
      routes[i]++
    } else if (fkind[i] == "E") unknown(i, ".Map" name)
  }
}
function scan_file(i,   f, line, sc, stmt, m, decl, nm, prm, rc) {
  f = fname[i]; sc = i SUBSEP ""; scope_ext[sc] = ""; scope_file[sc] = i; stmt = ""; curm = ""; lineno = 0
  while ((rc = (getline line < f)) > 0) {
    lineno++
    sub(/\r$/, "", line)
    line = strip_comment(line)
    if (line ~ /^[ \t]*$/) continue
    if (match(line, /const[ \t]+string[ \t]+[A-Za-z_][A-Za-z0-9_]*[ \t]*=[ \t]*"[^"]*"/)) {
      m = substr(line, RSTART, RLENGTH); sub(/^const[ \t]+string[ \t]+/, "", m)
      nm = m; sub(/[ \t]*=.*$/, "", nm); sub(/^[^"]*"/, "", m); sub(/"$/, "", m)
      konst[i, nm] = m
    }
    if (match(line, /^[ \t]*(public|private|internal|protected)[^=;(]*[ \t][A-Za-z_][A-Za-z0-9_]*[ \t]*\(/)) {
      m = substr(line, RSTART, RLENGTH); sub(/[ \t]*\($/, "", m); sub(/^.*[ \t]/, "", m)
      curm = m
      # A method starts a scope of its own: a helper is not part of the extension above it (the extension branch below overrides it).
      sc = i SUBSEP "m:" m; scope_ext[sc] = ""; scope_file[sc] = i
    }
    if (curm != "" && !((i, curm) in handler) && match(line, /I(Command|Query)Handler</)) handler[i, curm] = first_generic(substr(line, RSTART + RLENGTH))
    if (match(line, /Map[A-Za-z0-9_]*Endpoints[ \t]*\([ \t]*this[ \t]+[A-Za-z0-9_.<>]+[ \t]+[A-Za-z_][A-Za-z0-9_]*[ \t]*\)/)) {
      decl = substr(line, RSTART, RLENGTH); line = substr(line, RSTART + RLENGTH)
      nm = decl; sub(/[ \t]*\(.*$/, "", nm)
      prm = decl; sub(/[ \t]*\)$/, "", prm); sub(/^.*[ \t]/, "", prm)
      sc = i SUBSEP nm; scope_ext[sc] = nm; scope_file[sc] = i
      if (!(nm in ext_param)) { ext_param[nm] = prm; ext_file[nm] = i }
      else if (ext_file[nm] != i) fail("routes: extension " nm " declared twice: " fname[ext_file[nm]] ", " fname[i])
    }
    if (stmt == "" && line !~ /\.Map[A-Za-z0-9_]*[(<]/) continue
    stmt = (stmt == "" ? line : stmt " " line)
    if (index(line, ";") > 0) { process(i, sc, stmt); stmt = "" }
  }
  if (rc < 0) fail("routes: cannot read " f)
  if (stmt != "") process(i, sc, stmt)
  close(f)
}
# prefix: the route prefix of variable v in scope sc, or the error marker "\001".
function prefix(sc, v, depth,   key, ext, pp) {
  if (depth > 40) return "\001"
  key = sc SUBSEP v
  if (key in gpar) { pp = prefix(sc, gpar[key], depth + 1); return (pp == "\001" ? pp : join(pp, gpath[key])) }
  ext = scope_ext[sc]
  # Only the top level of the host (Program.cs, where `app` lives) is the root; any other scope without an extension is unknown.
  if (ext == "") return (fkind[scope_file[sc]] == "P" ? "" : "\001")
  if (v == ext_param[ext] && (ext in caller_var)) return prefix(caller_scope[ext], caller_var[ext], depth + 1)
  return "\001"
}
function fail(msg) { print msg > errfile; failed = 1; exit 3 }
{
  sub(/\r$/, "")
  n = split($0, seg, "/")
  kind = ""
  if (n >= 6 && seg[1] == "src" && seg[2] == "Modules" && seg[n - 1] == "Endpoints" && seg[n] ~ /.Endpoints\.cs$/) kind = "E"
  else if (n == 5 && seg[1] == "src" && seg[2] == "Modules" && seg[5] ~ /.Module\.cs$/) kind = "M"
  else if (n == 4 && seg[1] == "src" && seg[2] == "Host" && seg[4] == "Program.cs") kind = "P"
  if (kind != "") { nf++; fname[nf] = $0; fkind[nf] = kind; fmod[nf] = seg[3] }
}
END {
  if (failed) exit 3
  for (i = 1; i <= nf; i++) scan_file(i)
  for (i = 1; i <= nf; i++) {
    if (fkind[i] != "E" || (i in routes)) continue
    if ((i in groups) || (i in unknown_at)) fail("no routes parsed in " fname[i] ((i in unknown_at) ? " (" unknown_at[i] ")" : ""))
  }
  for (i = 1; i <= nf; i++) if (i in unknown_at) fail("routes: unknown mapping shape in " fname[i] ": " unknown_at[i])
  for (r = 1; r <= nr; r++) {
    i = rfile[r]; arg = rarg[r]
    if (substr(arg, 1, 1) == "\"") arg = substr(arg, 2, length(arg) - 2)
    else {
      nm = arg; sub(/^.*\./, "", nm)
      if (!((i, nm) in konst)) fail("routes: the route constant " arg " is not a const string in " fname[i])
      arg = konst[i, nm]
    }
    p = prefix(rscope[r], rvar[r], 0)
    if (p == "\001") fail("routes: cannot resolve the group prefix of " rvar[r] " in " fname[i] " (an extension nothing calls, or a receiver the parser does not know)")
    route = join(p, arg)
    if (substr(route, 1, 1) != "/") route = "/" route
    if (rperm[r] == "-") fail("routes: no authorization call on " route " in " fname[i] " (RequirePermission, AllowAnonymous or RequireAuthorization on the route itself; group-level authorization is not read)")
    h = ((i, rmeth[r]) in handler) ? handler[i, rmeth[r]] : "-"
    row = fmod[i] "|" rverb[r] "|" route "|" h "|" rperm[r] "|" fname[i]
    print row
  }
}'

# emit_routes: the routes shard (see routes_awk); one awk process for the whole tree.
emit_routes() {
  local rows_file="$work/routes.awk.out" err_file="$work/routes.awk.err" status=0 msg="" lines=()
  : > "$err_file"
  awk -v errfile="$err_file" "$routes_awk" < "$files_cache" > "$rows_file" || status=$?
  if (( status != 0 )); then
    [[ -s "$err_file" ]] && read -r msg < "$err_file"
    fail_parse "${msg:-routes: awk failed (exit $status)}"
  fi
  mapfile -t lines < "$rows_file"
  if (( ${#lines[@]} > 0 )); then printf '%s\n' "${lines[@]}"; fi
}

# cs_awk_lib: awk functions shared by the permissions and errors parsers.
#   cs_read(f)    reads a C# file whole (CR removed) into two strings of the same length, so that a position in one is the same position
#                 in the other: RAW, the text with every // and /* */ comment blanked to spaces (newlines kept), and MASK, RAW with the
#                 contents of every string and char literal replaced by "_" (the quotes kept). Structure is matched on MASK, so that a
#                 parenthesis, a comma or a name inside a string or a comment is never read as code; values are taken from RAW at the same
#                 positions. Regular, verbatim (@"", with "" inside) and interpolated strings are known; an interpolated string holding a
#                 quote inside a {hole} is not. Returns -1 when the file cannot be read.
#   line_at(p)    the line number of position p of MASK.
#   fail(msg)     writes msg to errfile and exits 3 (the shell turns it into exit 2).
# shellcheck disable=SC2016
cs_awk_lib='
function cs_read(f,   line, rc, n, k, c, d, r, m, st) {
  if (SQ == "") SQ = sprintf("%c", 39)
  RAW = ""; MASK = ""; st = 0
  while ((rc = (getline line < f)) > 0) {
    sub(/\r$/, "", line)
    n = length(line); r = ""; m = ""
    for (k = 1; k <= n; k++) {
      c = substr(line, k, 1); d = substr(line, k + 1, 1)
      if (st == 0) {
        if (c == "/" && d == "/") { for (; k <= n; k++) { r = r " "; m = m " " } break }
        if (c == "/" && d == "*") { r = r "  "; m = m "  "; k++; st = 4; continue }
        if (c == "\"") st = (substr(line, k - 1, 1) == "@" || substr(line, k - 2, 2) == "@$") ? 2 : 1
        else if (c == SQ) st = 5
        r = r c; m = m c
      } else if (st == 1 || st == 5) {
        if (c == "\\") { r = r c d; m = m "__"; k++ }
        else if ((st == 1 && c == "\"") || (st == 5 && c == SQ)) { r = r c; m = m c; st = 0 }
        else { r = r c; m = m "_" }
      } else if (st == 2) {
        if (c == "\"" && d == "\"") { r = r c d; m = m "__"; k++ }
        else if (c == "\"") { r = r c; m = m c; st = 0 }
        else { r = r c; m = m "_" }
      } else {
        if (c == "*" && d == "/") { r = r "  "; m = m "  "; k++; st = 0 }
        else { r = r " "; m = m " " }
      }
    }
    # A regular string or a char literal ends at the end of its line; a verbatim string or a block comment may go on.
    if (st == 1 || st == 5) st = 0
    RAW = RAW r "\n"; MASK = MASK m "\n"
  }
  close(f)
  return (rc < 0 ? -1 : 0)
}
function line_at(p,   s) { s = substr(MASK, 1, p); return gsub(/\n/, "", s) + 1 }
function fail(msg) { print msg > errfile; failed = 1; exit 3 }
'

# permissions_awk: one awk run over the tracked file list (stdin) that reads, under src/Modules/<Module>/:
#   C  *Permissions.cs       the constants: `const string Name = "module.resource.action";`, one per line, keyed by the enclosing class
#   S  *PermissionSource.cs  the records: a `Define(` or `new(` whose first argument is `XPermissions.Name`, up to its closing parenthesis;
#                            admin default is yes when `adminDefault: true` or `AdminDefault: true` is inside it, no when the flag is false
#                            or absent
# and prints code|module|yes or no|file of the constant, one row per constant (a constant with no record is no).
# Errors (exit 3, the message in errfile), so that no shape gives a wrong or missing row: a `const` in a constants file that is not that
# one-line shape; a constants file with no constant or a source file with no record; two constants with the same code; a record whose
# constant no constants file declares; a constant in two records; a reference to a permission constant that is not the first argument of
# a record (another record shape); an admin flag that is positional or not a literal true or false; a helper whose adminDefault defaults
# to true (an absent flag would then mean yes); a file that cannot be read.
# shellcheck disable=SC2016
permissions_awk="$cs_awk_lib"'
function read_constants(i,   f, nl, L, R, j, cls, cnt, ln, nm, code) {
  f = cfile[i]
  if (cs_read(f) < 0) fail("permissions: cannot read " f)
  nl = split(MASK, L, "\n"); split(RAW, R, "\n"); cls = ""; cnt = 0
  for (j = 1; j <= nl; j++) {
    if (match(L[j], /(^|[^A-Za-z0-9_])class[ \t]+[A-Za-z_][A-Za-z0-9_]*/)) { cls = substr(L[j], RSTART, RLENGTH); sub(/^.*[ \t]/, "", cls) }
    if (L[j] !~ /(^|[^A-Za-z0-9_])const([^A-Za-z0-9_]|$)/) continue
    if (!match(R[j], /const[ \t]+string[ \t]+[A-Za-z_][A-Za-z0-9_]*[ \t]*=[ \t]*"[a-z_]+\.[a-z_]+\.[a-z_]+"[ \t]*;/))
      fail("permissions: cannot read the constant at line " j " of " f " (expected `const string Name = \"module.resource.action\";` on one line)")
    ln = substr(R[j], RSTART, RLENGTH)
    nm = ln; sub(/^const[ \t]+string[ \t]+/, "", nm); sub(/[ \t]*=.*$/, "", nm)
    code = ln; sub(/^[^"]*"/, "", code); sub(/".*$/, "", code)
    if (cls == "") fail("permissions: the constant " nm " at line " j " of " f " is outside a class")
    if ((cls "." nm) in pcode) fail("permissions: the constant " cls "." nm " is declared twice: " pfile[cls "." nm] ", " f)
    if (code in bycode) fail("permissions: duplicate permission code " code " (" bycode[code] " in " pfile[bycode[code]] ", " cls "." nm " in " f ")")
    pcode[cls "." nm] = code; pfile[cls "." nm] = f; pmod[cls "." nm] = cmod[i]; bycode[code] = cls "." nm
    cnt++
  }
  if (cnt == 0) fail("permissions: no constant parsed in " f " (expected `const string Name = \"module.resource.action\";`)")
}
function read_source(i,   f, pos, abs, start, after, tok, depth, k, L, c, rec, flag, recs, total, m) {
  f = sfile[i]
  if (cs_read(f) < 0) fail("permissions: cannot read " f)
  if (MASK ~ /[aA]dminDefault[ \t\n]*=[ \t\n]*true/)
    fail("permissions: an adminDefault parameter that defaults to true in " f " (an absent flag would mean yes; the parser reads an absent flag as no)")
  pos = 1; recs = 0; L = length(MASK)
  while (match(substr(MASK, pos), /(^|[^A-Za-z0-9_])(Define|new)[ \t\n]*\(/)) {
    start = pos + RSTART - 1 + RLENGTH
    pos = start
    after = substr(MASK, start)
    if (!match(after, /^[ \t\n]*[A-Za-z_][A-Za-z0-9_]*Permissions\.[A-Za-z_][A-Za-z0-9_]*/)) continue
    tok = substr(after, RSTART, RLENGTH); gsub(/[ \t\n]/, "", tok)
    depth = 1
    for (k = start; k <= L && depth > 0; k++) {
      c = substr(MASK, k, 1)
      if (c == "(") depth++
      else if (c == ")") depth--
    }
    if (depth > 0) fail("permissions: the record of " tok " at line " line_at(start) " of " f " has no closing parenthesis")
    rec = substr(MASK, start, k - 1 - start)
    pos = k
    if (match(rec, /[aA]dminDefault[ \t\n]*:[ \t\n]*(true|false)([^A-Za-z0-9_]|$)/)) flag = (substr(rec, RSTART, RLENGTH) ~ /true/) ? "yes" : "no"
    else if (rec ~ /[aA]dminDefault/) fail("permissions: the admin flag of " tok " at line " line_at(start) " of " f " is not a literal true or false")
    else if (rec ~ /(^|[^A-Za-z0-9_])(true|false)([^A-Za-z0-9_]|$)/) fail("permissions: a positional admin flag in the record of " tok " at line " line_at(start) " of " f " (write AdminDefault: true or adminDefault: true)")
    else flag = "no"
    if (!(tok in pcode)) fail("permissions: the constant " tok " in " f " is not declared in any *Permissions.cs file")
    if (tok in recfile) fail("permissions: " tok " has two records: " recfile[tok] ", " f)
    recfile[tok] = f; admin[tok] = flag
    recs++
  }
  total = 0; m = MASK
  while (match(m, /[A-Za-z_][A-Za-z0-9_]*Permissions\.[A-Za-z_][A-Za-z0-9_]*/)) { total++; m = substr(m, RSTART + RLENGTH) }
  if (total != recs) fail("permissions: " (total - recs) " reference(s) to a permission constant in " f " are not the first argument of a Define(...) or new(...) record (a shape the parser does not know)")
  if (recs == 0) fail("permissions: no record parsed in " f " (expected Define(XPermissions.Name, ...) or new(XPermissions.Name, ...))")
}
{
  sub(/\r$/, "")
  n = split($0, seg, "/")
  if (n < 5 || seg[1] != "src" || seg[2] != "Modules") next
  if (seg[n] ~ /.Permissions\.cs$/) { nc++; cfile[nc] = $0; cmod[nc] = seg[3] }
  else if (seg[n] ~ /.PermissionSource\.cs$/) { ns++; sfile[ns] = $0 }
}
END {
  if (failed) exit 3
  for (i = 1; i <= nc; i++) read_constants(i)
  for (i = 1; i <= ns; i++) read_source(i)
  for (key in pcode) print pcode[key] "|" pmod[key] "|" ((key in admin) ? admin[key] : "no") "|" pfile[key]
}'

# run_awk <label> <program> <rows file> [awk -v assignments...]: runs one awk program over the tracked file list into the rows file; on a
# failure, exit 2 with the message the program wrote.
run_awk() {
  local label="$1" program="$2" rows_file="$3" err_file="$work/$1.awk.err" status=0 msg=""
  shift 3
  : > "$err_file"
  awk -v errfile="$err_file" "$@" "$program" < "$files_cache" > "$rows_file" || status=$?
  if (( status != 0 )); then
    [[ -s "$err_file" ]] && read -r msg < "$err_file"
    fail_parse "${msg:-$label: awk failed (exit $status)}"
  fi
}

# emit_permissions: the permissions shard (see permissions_awk); one awk process for the whole tree.
emit_permissions() {
  local rows_file="$work/permissions.awk.out" lines=()
  run_awk permissions "$permissions_awk" "$rows_file"
  mapfile -t lines < "$rows_file"
  if (( ${#lines[@]} > 0 )); then printf '%s\n' "${lines[@]}"; fi
}

# errors_awk: one awk run over the tracked file list (stdin) that reads, under src/:
#   R  <X>ErrorMessages.resx (neutral: no culture part such as .ms. or .zh-Hans.)   the keys: `<data name="key"` (XML comments skipped)
#   E  *Errors.cs (modules and building blocks)   the declarations: each `Error.<Factory>(` call; the code is its first argument, a string
#      literal on the same or a later line, or a `const string` of the same file; the status comes from the factory
# and prints table 1 (code|module|http|resource key|file; the resource key is the code when a neutral resx has it, else -) on stdout and
# table 2 (key|http|resx file: the neutral keys that no declaration has; http is NNN for http.NNN, else -) into the file out2. The module
# is the folder under src/Modules, or the building-block directory under src/BuildingBlocks without its first dotted part.
# Errors (exit 3, the message in errfile), so that no shape gives a wrong or missing row: a factory the status map does not know; a code
# argument that is not a plain string literal or a const string of the file (a qualified constant must name a class of the file); a code with a character outside [A-Za-z0-9_.-]; a `const`
# that is not `const string Name = "literal";`; a code-shaped string literal ("a.b") in an *Errors.cs file that no factory call declares
# (another declaration shape); an *Errors.cs file with no declaration; the same code declared twice; a neutral resx with no key, a key
# twice in one file, or a <data element whose name is not on its line; a file that cannot be read.
# shellcheck disable=SC2016
errors_awk="$cs_awk_lib"'
function read_resx(i,   f, line, rc, lineno, incom, p, q, t, piece, key, cnt) {
  f = rfile[i]; lineno = 0; incom = 0; cnt = 0
  while ((rc = (getline line < f)) > 0) {
    lineno++
    sub(/\r$/, "", line)
    t = ""
    while (line != "") {
      if (incom) {
        q = index(line, "-->")
        if (q == 0) line = ""
        else { line = substr(line, q + 3); incom = 0 }
      } else {
        p = index(line, "<!--")
        if (p == 0) { t = t line; line = "" }
        else { t = t substr(line, 1, p - 1); line = substr(line, p + 4); incom = 1 }
      }
    }
    while (match(t, /<data([ \t>\/]|$)/)) {
      piece = substr(t, RSTART)
      if (!match(piece, /^<data[ \t]+name="[^"]+"/)) fail("errors: cannot read the <data> element at line " lineno " of " f " (expected <data name=\"key\" on one line)")
      key = substr(piece, 1, RLENGTH); sub(/^[^"]*"/, "", key); sub(/"$/, "", key)
      if ((f, key) in seen) fail("errors: the key " key " is declared twice in " f)
      seen[f, key] = 1
      nk++; rkey[nk] = key; rkfile[nk] = f; haskey[key] = 1
      cnt++
      t = substr(piece, RLENGTH + 1)
    }
  }
  if (rc < 0) fail("errors: cannot read " f)
  close(f)
  if (cnt == 0) fail("errors: no <data name=\"key\"> entry in the neutral resource file " f)
}
function read_errors(i,   f, pos, abs, tok, fac, st, p, a, code, id, nm, decl, at, lit, q) {
  f = efile[i]; decl = 0
  if (cs_read(f) < 0) fail("errors: cannot read " f)
  split("", konst); split("", produced); split("", fclass)
  a = MASK
  while (match(a, /(^|[^A-Za-z0-9_])class[ \t\n]+[A-Za-z_][A-Za-z0-9_]*/)) {
    nm = substr(a, RSTART, RLENGTH); sub(/^.*[ \t\n]/, "", nm); fclass[nm] = 1
    a = substr(a, RSTART + RLENGTH)
  }
  pos = 1
  while (match(substr(MASK, pos), /(^|[^A-Za-z0-9_])const([^A-Za-z0-9_]|$)/)) {
    abs = pos + RSTART - 1; if (substr(MASK, abs, 1) != "c") abs++
    pos = abs + 5
    a = substr(MASK, abs)
    if (!match(a, /^const[ \t\n]+string[ \t\n]+[A-Za-z_][A-Za-z0-9_]*[ \t\n]*=[ \t\n]*"_*"[ \t\n]*;/))
      fail("errors: cannot read the constant at line " line_at(abs) " of " f " (expected `const string Name = \"literal\";`)")
    nm = substr(a, 1, RLENGTH); sub(/^const[ \t\n]+string[ \t\n]+/, "", nm); sub(/[ \t\n]*=.*$/, "", nm)
    p = abs + index(a, "\"")
    lit = substr(RAW, p, index(substr(MASK, p), "\"") - 1)
    if (nm in konst) fail("errors: the constant " nm " is declared twice in " f)
    konst[nm] = lit
  }
  pos = 1
  while (match(substr(MASK, pos), /(^|[^A-Za-z0-9_])Error\.[A-Za-z_][A-Za-z0-9_]*[ \t\n]*\(/)) {
    abs = pos + RSTART - 1; tok = substr(MASK, abs, RLENGTH)
    pos = abs + RLENGTH
    at = line_at(abs + 1)
    fac = tok; sub(/^.*Error\./, "", fac); sub(/[ \t\n]*\($/, "", fac)
    if (!(fac in status)) fail("errors: unknown factory Error." fac " at line " at " of " f " (known: Validation, Unauthorized, Forbidden, NotFound, Conflict, Failure, Unavailable)")
    a = substr(MASK, pos); match(a, /^[ \t\n]*/); p = pos + RLENGTH; a = substr(MASK, p)
    if (match(a, /^"_*"[ \t\n]*[,)]/)) {
      code = substr(RAW, p + 1, index(substr(a, 2), "\"") - 1)
    } else if (match(a, /^[A-Za-z_][A-Za-z0-9_.]*[ \t\n]*[,)]/)) {
      id = substr(a, 1, RLENGTH - 1); gsub(/[ \t\n]/, "", id)
      nm = id; sub(/^.*\./, "", nm)
      q = id; if (!sub(/\.[A-Za-z0-9_]*$/, "", q)) q = ""
      sub(/^.*\./, "", q)
      if (q != "" && !(q in fclass)) fail("errors: the code " id " of Error." fac " at line " at " of " f " names a class this file does not declare")
      if (!(nm in konst)) fail("errors: cannot resolve the code " id " of Error." fac " at line " at " of " f " (not a string literal or a const string of the file)")
      code = konst[nm]
    } else fail("errors: the code of Error." fac " at line " at " of " f " is not a string literal or a const string of the file")
    if (code !~ /^[A-Za-z0-9_.-]+$/) fail("errors: the code \"" code "\" of Error." fac " at line " at " of " f " has a character outside [A-Za-z0-9_.-]")
    if (code in dfile) fail("errors: duplicate error code " code " (" dfile[code] ", " f " line " at ")")
    dfile[code] = f; produced[code] = 1
    nd++; dcode[nd] = code; dmod[nd] = emod[i]; dstatus[nd] = status[fac]; dpath[nd] = f
    decl++
  }
  pos = 1
  while (match(substr(MASK, pos), /"_*"/)) {
    abs = pos + RSTART - 1; pos = abs + RLENGTH
    lit = substr(RAW, abs + 1, RLENGTH - 2)
    if (lit ~ /^[a-z0-9_]+(\.[a-z0-9_]+)+$/ && !(lit in produced))
      fail("errors: the code-like string \"" lit "\" at line " line_at(abs) " of " f " is not the code of an Error.<Factory>(...) call (a declaration shape the parser does not know)")
  }
  if (decl == 0) fail("errors: no error code declaration parsed in " f " (expected Error.<Factory>(\"code\", ...))")
}
BEGIN {
  status["Validation"] = 400; status["Unauthorized"] = 401; status["Forbidden"] = 403; status["NotFound"] = 404
  status["Conflict"] = 409; status["Failure"] = 500; status["Unavailable"] = 503
}
{
  sub(/\r$/, "")
  n = split($0, seg, "/")
  if (n < 3 || seg[1] != "src") next
  if (seg[n] ~ /^[A-Za-z0-9_]+ErrorMessages\.resx$/) { nr++; rfile[nr] = $0 }
  else if (seg[n] ~ /.Errors\.cs$/) {
    ne++; efile[ne] = $0
    mod = (n >= 4 ? seg[3] : seg[2])
    if (seg[2] != "Modules") sub(/^[^.]*\./, "", mod)
    emod[ne] = mod
  }
}
END {
  if (failed) exit 3
  for (i = 1; i <= nr; i++) read_resx(i)
  for (i = 1; i <= ne; i++) read_errors(i)
  for (d = 1; d <= nd; d++) print dcode[d] "|" dmod[d] "|" dstatus[d] "|" ((dcode[d] in haskey) ? dcode[d] : "-") "|" dpath[d]
  printf "" > out2
  for (k = 1; k <= nk; k++) {
    if (rkey[k] in dfile) continue
    print rkey[k] "|" (rkey[k] ~ /^http\.[0-9][0-9][0-9]$/ ? substr(rkey[k], 6) : "-") "|" rkfile[k] > out2
  }
}'

# errors_pass: runs errors_awk once; table 1 goes to errors.table1, table 2 to errors.table2 (both in work; not errors.rows2, which
# generate truncates to receive the output of emit_errors_2). errors_done records the run so that emit_errors_2 after emit_errors (as
# generate calls them, in the same shell) does not parse the tree again.
errors_done=""
errors_pass() {
  run_awk errors "$errors_awk" "$work/errors.table1" -v out2="$work/errors.table2"
  errors_done="$work"
}

# emit_errors: table 1 of the errors shard (declared codes).
emit_errors() {
  local lines=()
  errors_pass
  mapfile -t lines < "$work/errors.table1"
  if (( ${#lines[@]} > 0 )); then printf '%s\n' "${lines[@]}"; fi
}

# emit_errors_2: table 2 of the errors shard (resource-only keys), with its note when it has rows.
emit_errors_2() {
  local lines=()
  [[ "$errors_done" == "$work" ]] || errors_pass
  mapfile -t lines < "$work/errors.table2"
  if (( ${#lines[@]} > 0 )); then
    table_note='Neutral resource keys that no `*Errors.cs` file declares: codes set as string constants elsewhere (middleware, exception handlers, validation) or `http.NNN` keys for a bare HTTP status.'
    printf '%s\n' "${lines[@]}"
  fi
}

# scan_markers: "file:line:text" for every line of every file that the whole-line marker rule matches (grep -I skips binary files).
# The sh wrapper turns grep's "nothing matched" (1) into success for a batch of files, so that any other status is a real failure.
scan_markers() {
  list_files | tr '\n' '\0' | xargs -0 -r sh -c \
    'grep -E -I -n -H -e "$0" -- "$@" || { s=$?; [ "$s" -eq 1 ] || exit "$s"; }' "$marker_line"
}

# emit_markers: one row per file: file | kinds | expressions. Kinds are the distinct forms (//#if, <!--#if, %%#if, #if) of the matching
# lines, sorted, joined with ", "; expressions are the distinct text inside the first parentheses of the #if lines (nested parentheses
# kept), sorted, joined with "; "; "-" when there is none.
emit_markers() {
  local raw="$work/markers.raw" status=0
  scan_markers > "$raw" || status=$?
  (( status == 0 )) || fail_parse "grep failed (exit $status) while searching for template markers"
  tr -d '\r' < "$raw" \
    | awk '
      {
        i = index($0, ":"); file = substr($0, 1, i - 1)
        rest = substr($0, i + 1); j = index(rest, ":"); text = substr(rest, j + 1)
        sub(/^[ \t]+/, "", text)
        if (substr(text, 1, 2) == "//") { kind = "//#if"; text = substr(text, 3) }
        else if (substr(text, 1, 4) == "<!--") { kind = "<!--#if"; text = substr(text, 5) }
        else if (substr(text, 1, 2) == "%%") { kind = "%%#if"; text = substr(text, 3) }
        else kind = "#if"
        print file "\t1\t" kind
        if (text ~ /^#if([ \t]|\()/) {
          p = index(text, "(")
          if (p > 0) {
            depth = 0; expr = ""
            for (k = p; k <= length(text); k++) {
              c = substr(text, k, 1)
              if (c == "(") { depth++; if (depth == 1) continue }
              else if (c == ")") { depth--; if (depth == 0) break }
              expr = expr (c == "|" ? "\\|" : c)
            }
            gsub(/^[ \t]+/, "", expr); gsub(/[ \t]+$/, "", expr)
            if (expr != "") print file "\t2\t" expr
          }
        }
      }' \
    | sort -u \
    | awk '
      function flush() { if (cur != "") print cur "|" (kinds == "" ? "-" : kinds) "|" (exprs == "" ? "-" : exprs) }
      {
        i = index($0, "\t"); file = substr($0, 1, i - 1); rest = substr($0, i + 1); t = substr(rest, 1, 1); val = substr(rest, 3)
        if (file != cur) { flush(); cur = file; kinds = ""; exprs = "" }
        if (t == "1") kinds = kinds (kinds == "" ? "" : ", ") val
        else exprs = exprs (exprs == "" ? "" : "; ") val
      }
      END { flush() }'
}

# generate: writes every shard into shard_dir, always a directory of the temporary work area: the write mode copies the result to --out
# only after every shard succeeded, and --check compares it with --out.
generate() {
  local name rows rows2
  mkdir -p "$shard_dir"
  for name in $shards; do
    rows="$work/$name.rows"
    "emit_$name" > "$rows"
    shard_meta "$name"
    shard_begin "$name" "$title_text"
    shard_table "$heading1" "" "$header_text" "$rows"
    if [[ -n "$header2_text" ]]; then
      rows2="$work/$name.rows2"
      table_note=""
      "emit_${name}_2" > "$rows2"
      shard_table "$heading2" "$table_note" "$header2_text" "$rows2"
    fi
    shard_end
  done
}

# check_map: the MAP.md rules; prints one line per problem and returns 1 when there is any.
check_map() {
  local map="$out/MAP.md" problem=0 token name line text="" bt='`' pattern checked=" "
  local lines=()
  if [[ ! -f "$map" ]]; then
    echo "project-index: MAP.md is missing in $out" >&2
    return 1
  fi
  pattern="$bt([^$bt]+)$bt"
  mapfile -t lines < "$map"
  # Every backticked repository path must exist. A token with a space, a brace, a star, an angle bracket or an ellipsis is a pattern
  # or a placeholder, not a path. Bash builtins only (no process per line); a CR at the end of a line is dropped.
  for line in "${lines[@]}"; do
    line="${line%$'\r'}"
    text+="$line"$'\n'
    while [[ "$line" =~ $pattern ]]; do
      token="${BASH_REMATCH[1]}"
      line="${line#*"${BASH_REMATCH[0]}"}"
      case "$token" in
        src/* | tests/* | build/* | docs/* | .github/*) ;;
        *) continue ;;
      esac
      case "$token" in
        *" "* | *"{"* | *"*"* | *"<"* | *"..."*) continue ;;
      esac
      [[ "$checked" == *" $token "* ]] && continue
      checked+="$token "
      if [[ ! -e "$root/$token" ]]; then
        echo "project-index: MAP.md names a path that does not exist: $token" >&2
        problem=1
      fi
    done
  done
  for name in $shards; do
    if [[ "$text" != *"$name.md"* ]]; then
      echo "project-index: MAP.md does not name the shard file: $name.md" >&2
      problem=1
    fi
  done
  if (( ${#lines[@]} > 120 )); then
    echo "project-index: MAP.md has ${#lines[@]} lines, at most 120 are allowed" >&2
    problem=1
  fi
  return "$problem"
}

# check_mode: generates into a temporary directory and compares it with --out, then checks MAP.md.
check_mode() {
  local name file base known status=0
  shard_dir="$work/generated"
  generate
  for name in $shards; do
    if [[ ! -f "$out/$name.md" ]]; then
      echo "project-index: missing: $name" >&2
      status=1
    elif ! cmp -s "$shard_dir/$name.md" "$out/$name.md"; then
      echo "project-index: stale: $name" >&2
      status=1
    fi
  done
  for file in "$out"/*.md; do
    [[ -e "$file" ]] || continue
    base="${file##*/}"
    [[ "$base" == "MAP.md" ]] && continue
    known=0
    for name in $shards; do
      if [[ "$base" == "$name.md" ]]; then known=1; fi
    done
    if (( known == 0 )); then
      echo "project-index: unknown shard: $base" >&2
      status=1
    fi
  done
  check_map || status=1
  if (( status != 0 )); then
    echo "project-index: fix the cause, then regenerate with: bash build/scripts/project-index.sh (a conflict in a shard is regenerated, never merged by hand)" >&2
  fi
  return "$status"
}

main() {
  local mode="write" script_dir
  script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
  while (( $# > 0 )); do
    case "$1" in
      --check) mode="check"; shift ;;
      --root)
        (( $# >= 2 )) && [[ "$2" != --* ]] || fail "--root needs a directory"
        root="$2"; shift 2 ;;
      --out)
        (( $# >= 2 )) && [[ "$2" != --* ]] || fail "--out needs a directory"
        out="$2"; shift 2 ;;
      *) fail "unknown argument: $1 (usage: project-index.sh [--check] [--root DIR] [--out DIR])" ;;
    esac
  done
  [[ -n "$root" ]] || root="$script_dir/../.."
  [[ -d "$root" ]] || fail "not a directory: $root"
  # --out may be relative to where the script was started, and may not exist yet: make it absolute before changing directory.
  if [[ -z "$out" ]]; then
    out="$root/docs/superpowers/index"
  fi
  case "$out" in
    /* | [A-Za-z]:*) ;;
    *) out="$PWD/$out" ;;
  esac
  root="$(cd "$root" && pwd)"
  cd "$root"
  work="$(mktemp -d)"
  trap 'rm -rf "$work"' EXIT
  prepare_files
  if [[ "$mode" == "check" ]]; then
    check_mode
  else
    # Atomic: a parse error on any shard leaves --out as it was.
    shard_dir="$work/generated"
    generate
    mkdir -p "$out"
    cp "$shard_dir"/*.md "$out"/
  fi
}

# Run main only when executed; the tests source this file to call need_rows, check_map, main and the shard functions.
if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
  main "$@"
fi
