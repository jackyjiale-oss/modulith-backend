#!/usr/bin/env bash
# Generates the project index (project index design): eight shards under docs/superpowers/index/ that list routes, permissions, error
# codes, events, jobs, configuration, tests and template switch markers, so that none of them has to be found with a wide search.
# It reads the tree it is run in and hard-codes no module name. MAP.md in the same directory is hand-written; --check keeps it honest.
#
# Usage: bash build/scripts/project-index.sh [--check] [--root DIR] [--out DIR]
#   no argument  rewrite every shard in --out
#   --check      rewrite nothing: generate into a temporary directory with the same code, compare it byte for byte with --out and check
#                MAP.md (it exists, every repository path it names exists, it names every shard, at most 120 lines)
#   --root DIR   the tree to read (default: two levels above this script)
#   --out DIR    where the shards and MAP.md are (default: <root>/docs/superpowers/index)
# Output: shards are deterministic (LC_ALL=C, LF, no timestamps), so --check gives the same answer on Windows and on Linux.
# Exit: 0 ok, 1 --check found a stale or missing shard, an unknown shard file or a MAP.md problem, 2 usage or parse error (a source that
# yields zero rows although the tree has some is a parse error, never an empty table).
#
# For the functions below that print rows (emit_<shard>): one record per line, fields separated by "|" in the column order of the shard,
# unsorted; a literal "|" inside a field is written "\|". write_shard sorts the rows and renders the table.
set -euo pipefail

export LC_ALL=C

fail() { echo "project-index: $*" >&2; exit 2; }
fail_parse() { fail "$*"; }

# The shard names, in the order MAP.md must list them; each is a file <name>.md.
shards="routes permissions errors events jobs config tests markers"

banner='<!-- Generated by build/scripts/project-index.sh; do not edit. Regenerate with: bash build/scripts/project-index.sh -->'

# The whole-line marker rule of template-smoke.sh (a line that only quotes a marker inline is prose, not a marker), with the slash
# escapes removed: "\/" means "/" but makes GNU grep 3.8 and newer warn about a stray backslash; the lines matched are the same.
marker_line='^[[:space:]]*(//|<!--|%%)?#(if|elseif|else|endif)([[:space:]]|\(|-->|$)'

# Set by main: root, out (absolute), work (a temporary directory), shard_dir (where generate writes) and files_cache.
root="" out="" work="" shard_dir="" files_cache=""

# prepare_files: lists the files of the tree once, relative to the root and sorted, into files_cache. With a .git (a directory, or a file
# in a git worktree) the list is git ls-files (tracked files only, minus the ones deleted from the working copy); else find, which
# skips bin, obj and .git.
prepare_files() {
  files_cache="$work/files.txt"
  if [[ -e "$root/.git" ]]; then
    git -C "$root" ls-files -z > "$work/ls.z" || fail_parse "git ls-files failed in $root"
    git -C "$root" ls-files -z --deleted > "$work/deleted.z" || fail_parse "git ls-files --deleted failed in $root"
    tr '\0' '\n' < "$work/ls.z" | sort -u > "$work/tracked.txt"
    tr '\0' '\n' < "$work/deleted.z" | sort -u > "$work/deleted.txt"
    comm -23 "$work/tracked.txt" "$work/deleted.txt" > "$files_cache"
  else
    (cd "$root" && find . -type f -not -path '*/bin/*' -not -path '*/obj/*' -not -path '*/.git/*' -print) \
      | sed 's|^\./||' | sort -u > "$files_cache"
  fi
}

# list_files: the relative paths of the tree, sorted, one per line.
list_files() {
  cat "$files_cache"
}

# need_rows <shard> <count> [sources]: a parse error (exit 2) when a shard has no rows although the tree has sources for it. sources is
# the number of source files found and must be numeric (default 1: the caller only asks when it found some).
need_rows() {
  local shard="$1" count="$2" sources="${3-1}"
  if (( sources > 0 && count == 0 )); then
    fail_parse "$shard: no rows although the tree has $sources source file(s) for it; the parser does not know their shape"
  fi
}

# render_rows: turns "|"-separated records on stdin into pipe-table rows ("\|" stays a literal pipe inside a cell).
render_rows() {
  sed -E -e 's/\\\|/\x01/g' -e 's/\|/ | /g' -e 's/\x01/\\|/g' -e 's/^/| /' -e 's/$/ |/'
}

# A shard file is built in three steps, with Bash builtins for all but the sort of the rows (a process costs a lot on Windows):
#   shard_begin <name> <title>
#   shard_table <heading> <note> <header-row> <rows-file>   (once for each table, in order)
#   shard_end
# writes <shard_dir>/<name>.md: the banner, "# title", "Rows: N", then the tables. "Rows: N" is the TOTAL number of data rows over all the
# tables of the shard. A table is its optional "## heading" line, its optional free-text note line, the header row, the separator and the
# rows sorted with LC_ALL=C; tables are separated by one blank line. The header row is "|"-separated like a record (see the top of this
# file); the rows are rendered, then sorted. An empty heading or note is left out, and an empty rows file needs no sort.
shard_name="" shard_title="" shard_body="" shard_rows=0 shard_tables=0
shard_begin() {
  shard_name="$1" shard_title="$2" shard_body="" shard_rows=0 shard_tables=0
}

shard_table() {
  local heading="$1" note="$2" header="$3" rows_file="$4"
  local sorted="$work/$shard_name.$shard_tables.sorted" lines=() columns=() separator="|" piece i
  if [[ -s "$rows_file" ]]; then
    render_rows < "$rows_file" | sort > "$sorted"
    mapfile -t lines < "$sorted"
  fi
  IFS='|' read -r -a columns <<< "$header"
  for i in "${columns[@]}"; do separator+=" --- |"; done
  if (( shard_tables > 0 )); then shard_body+=$'\n'; fi
  if [[ -n "$heading" ]]; then
    printf -v piece '## %s\n\n' "$heading"
    shard_body+="$piece"
  fi
  if [[ -n "$note" ]]; then
    printf -v piece '%s\n\n' "$note"
    shard_body+="$piece"
  fi
  printf -v piece '| %s |\n%s\n' "${header//|/ | }" "$separator"
  shard_body+="$piece"
  if (( ${#lines[@]} > 0 )); then
    printf -v piece '%s\n' "${lines[@]}"
    shard_body+="$piece"
  fi
  shard_rows=$((shard_rows + ${#lines[@]}))
  shard_tables=$((shard_tables + 1))
}

shard_end() {
  printf '%s\n\n# %s\n\nRows: %s\n\n%s' "$banner" "$shard_title" "$shard_rows" "$shard_body" > "$shard_dir/$shard_name.md"
}

# write_shard <name> <title> <header-row> <rows-file>: a shard with one table and no heading.
write_shard() {
  shard_begin "$1" "$2"
  shard_table "" "" "$3" "$4"
  shard_end
}

# shard_meta <name>: sets the title and the tables of a shard: title_text; heading1 and header_text (the "|"-separated column names of
# table 1); heading2 and header2_text (table 2, empty when the shard has one table). No subshell: a fork costs a lot on Windows.
# A shard with two tables has emit_<name> (rows of table 1) and emit_<name>_2 (rows of table 2); the latter may set table_note, the line
# printed under the heading of table 2 (reset to empty before each call).
title_text="" heading1="" header_text="" heading2="" header2_text="" table_note=""
shard_meta() {
  heading1="" heading2="" header2_text=""
  case "$1" in
    routes) title_text="Routes"; header_text="module|method|route|handler|permission|file" ;;
    permissions) title_text="Permissions"; header_text="code|module|admin default|file" ;;
    errors)
      title_text="Error codes"
      heading1="Declared codes"; header_text="code|module|http|resource key|file"
      heading2="Resource-only keys"; header2_text="key|http|resx file" ;;
    events) title_text="Integration events"; header_text="event|publisher|handlers" ;;
    jobs) title_text="Recurring jobs"; header_text="job|module|config keys|file" ;;
    config) title_text="Configuration sections"; header_text="section|owner|documented in" ;;
    tests)
      title_text="Tests"
      heading1="Folders"; header_text="test project|folder|source area|files"
      heading2="Name pairs"; header2_text="source|test" ;;
    markers) title_text="Template switch markers"; header_text="file|kinds|expressions" ;;
    *) fail "no title or header for shard $1" ;;
  esac
}

# routes_awk: one awk run over the tracked file list (stdin, from files_cache) that reads the C# files it needs with getline. Three kinds:
#   E  src/Modules/<Module>/<Project>/.../Endpoints/*Endpoints.cs   the routes; only these give rows
#   M  src/Modules/<Module>/<Project>/*Module.cs                    module extensions that call the endpoint extensions
#   P  src/Host/<Project>/Program.cs                                the host: `var api = app.MapGroup("/api/v1"); api.MapXEndpoints();`
# Pass 1 (scan_file) reads each file line by line (CR and // comments removed) and records, per scope (a file and the Map...Endpoints
# extension being read, any other method, or the top level of the file): `var X = Y.MapGroup("p")` (group X under Y),
# `X.MapFooEndpoints()` calls (Foo takes the prefix of X in the caller's scope), `MapFooEndpoints(this T P)` declarations (P is the
# caller's group), `const string N = "v"`, the first generic argument of the ICommandHandler<...> or IQueryHandler<...> parameter of
# each method, and each statement (from a line with `.Map` to the line with `;`) holding `X.Map(Get|Post|Put|Patch|Delete)(route,
# Method)` with its chained RequirePermission(P) / AllowAnonymous() / RequireAuthorization() (authenticated) / RequireAuthorization("N")
# (the policy N). Pass 2 (END) resolves each route's prefix through the group and caller chain (only the top level of Program.cs is the
# root, where `app` lives) and prints module|METHOD|route|handler|permission|file.
# Errors (exit 3, the message in errfile), so that no shape gives a wrong row: an endpoint file with MapGroup or a Map...Endpoints call
# but zero routes; any other .MapX call in an endpoint file; an extension called from two places or declared in two files; a prefix that
# cannot be resolved (an extension not named Map...Endpoints or not on one line, a helper method); a route with no authorization call of
# its own (group-level authorization is not read); a file that cannot be read.
# shellcheck disable=SC2016
routes_awk='
function strip_comment(s,   k, c, n, inq) {
  if (index(s, "//") == 0) return s
  inq = 0; n = length(s)
  for (k = 1; k <= n; k++) {
    c = substr(s, k, 1)
    if (inq && c == "\\") { k++; continue }
    if (c == "\"") inq = !inq
    else if (!inq && c == "/" && substr(s, k + 1, 1) == "/") return substr(s, 1, k - 1)
  }
  return s
}
function first_generic(s,   k, c, depth, out) {
  depth = 0; out = ""
  for (k = 1; k <= length(s); k++) {
    c = substr(s, k, 1)
    if (c == "<") depth++
    else if (c == ">") { if (depth == 0) break; depth-- }
    else if (c == "," && depth == 0) break
    out = out c
  }
  gsub(/[ \t]/, "", out)
  return out
}
function join(a, b,   r) {
  sub(/^\/+/, "", b)
  r = (b == "" ? a : a "/" b)
  gsub(/\/\/+/, "/", r)
  if (r != "/") sub(/\/$/, "", r)
  return r
}
function unknown(i, what) {
  if (!(i in unknown_at)) unknown_at[i] = what " at line " lineno
}
# process: one statement of file i in scope sc; each .MapX occurrence is handled at its position.
function process(i, sc, stmt,   rest, before, after, tok, name, recv, x, arg, meth, perm, p, key) {
  rest = stmt
  while (match(rest, /\.Map[A-Za-z0-9_]*[(<]/)) {
    before = substr(rest, 1, RSTART - 1); tok = substr(rest, RSTART, RLENGTH); after = substr(rest, RSTART + RLENGTH)
    rest = after
    name = substr(tok, 5, length(tok) - 5)
    recv = ""
    if (match(before, /[A-Za-z_][A-Za-z0-9_]*[ \t]*$/)) { recv = substr(before, RSTART, RLENGTH); sub(/[ \t]+$/, "", recv); before = substr(before, 1, RSTART - 1) }
    if (name == "Group" && substr(tok, length(tok)) == "(") {
      if (recv != "" && match(after, /^[ \t]*"[^"]*"[ \t]*\)/) && match(before, /[A-Za-z_][A-Za-z0-9_]*[ \t]*=[ \t]*$/)) {
        x = substr(before, RSTART, RLENGTH); sub(/[ \t]*=[ \t]*$/, "", x)
        match(after, /"[^"]*"/); p = substr(after, RSTART + 1, RLENGTH - 2)
        key = sc SUBSEP x
        gpar[key] = recv; gpath[key] = p
        if (fkind[i] == "E") groups[i]++
      } else if (fkind[i] == "E") unknown(i, ".MapGroup without `var X = Y.MapGroup(\"literal\")`")
    } else if (name ~ /Endpoints$/ && substr(tok, length(tok)) == "(") {
      if (recv == "") { if (fkind[i] == "E") unknown(i, ".Map" name " without a receiver"); continue }
      if (fkind[i] == "E") groups[i]++
      if (!(("Map" name) in caller_var)) { caller_scope["Map" name] = sc; caller_var["Map" name] = recv }
      else if (caller_scope["Map" name] != sc || caller_var["Map" name] != recv) fail("routes: extension Map" name " called from two places in " fname[i])
    } else if (name ~ /^(Get|Post|Put|Patch|Delete)$/ && substr(tok, length(tok)) == "(") {
      if (fkind[i] != "E") continue
      if (recv == "" || !match(after, /^[ \t]*("[^"]*"|[A-Za-z_][A-Za-z0-9_.]*)[ \t]*,[ \t]*[A-Za-z_][A-Za-z0-9_]*[ \t]*\)/)) {
        unknown(i, ".Map" name " whose arguments are not (route, Method)"); continue
      }
      arg = substr(after, RSTART, RLENGTH)
      meth = arg; sub(/^.*,[ \t]*/, "", meth); sub(/[ \t]*\)$/, "", meth)
      match(arg, /^[ \t]*("[^"]*"|[A-Za-z_][A-Za-z0-9_.]*)/); arg = substr(arg, RSTART, RLENGTH); sub(/^[ \t]+/, "", arg)
      perm = "-"
      if (match(after, /RequirePermission\([^)]*\)/)) { perm = substr(after, RSTART + 18, RLENGTH - 19); gsub(/[ \t]/, "", perm) }
      else if (after ~ /AllowAnonymous\([ \t]*\)/) perm = "anonymous"
      else if (match(after, /RequireAuthorization\([^)]*\)/)) {
        perm = substr(after, RSTART + 21, RLENGTH - 22); gsub(/[ \t"]/, "", perm)
        if (perm == "") perm = "authenticated"
      }
      nr++; rfile[nr] = i; rscope[nr] = sc; rvar[nr] = recv; rverb[nr] = toupper(name); rarg[nr] = arg; rmeth[nr] = meth; rperm[nr] = perm
      routes[i]++
    } else if (fkind[i] == "E") unknown(i, ".Map" name)
  }
}
function scan_file(i,   f, line, sc, stmt, m, decl, nm, prm, rc) {
  f = fname[i]; sc = i SUBSEP ""; scope_ext[sc] = ""; scope_file[sc] = i; stmt = ""; curm = ""; lineno = 0
  while ((rc = (getline line < f)) > 0) {
    lineno++
    sub(/\r$/, "", line)
    line = strip_comment(line)
    if (line ~ /^[ \t]*$/) continue
    if (match(line, /const[ \t]+string[ \t]+[A-Za-z_][A-Za-z0-9_]*[ \t]*=[ \t]*"[^"]*"/)) {
      m = substr(line, RSTART, RLENGTH); sub(/^const[ \t]+string[ \t]+/, "", m)
      nm = m; sub(/[ \t]*=.*$/, "", nm); sub(/^[^"]*"/, "", m); sub(/"$/, "", m)
      konst[i, nm] = m
    }
    if (match(line, /^[ \t]*(public|private|internal|protected)[^=;(]*[ \t][A-Za-z_][A-Za-z0-9_]*[ \t]*\(/)) {
      m = substr(line, RSTART, RLENGTH); sub(/[ \t]*\($/, "", m); sub(/^.*[ \t]/, "", m)
      curm = m
      # A method starts a scope of its own: a helper is not part of the extension above it (the extension branch below overrides it).
      sc = i SUBSEP "m:" m; scope_ext[sc] = ""; scope_file[sc] = i
    }
    if (curm != "" && !((i, curm) in handler) && match(line, /I(Command|Query)Handler</)) handler[i, curm] = first_generic(substr(line, RSTART + RLENGTH))
    if (match(line, /Map[A-Za-z0-9_]*Endpoints[ \t]*\([ \t]*this[ \t]+[A-Za-z0-9_.<>]+[ \t]+[A-Za-z_][A-Za-z0-9_]*[ \t]*\)/)) {
      decl = substr(line, RSTART, RLENGTH); line = substr(line, RSTART + RLENGTH)
      nm = decl; sub(/[ \t]*\(.*$/, "", nm)
      prm = decl; sub(/[ \t]*\)$/, "", prm); sub(/^.*[ \t]/, "", prm)
      sc = i SUBSEP nm; scope_ext[sc] = nm; scope_file[sc] = i
      if (!(nm in ext_param)) { ext_param[nm] = prm; ext_file[nm] = i }
      else if (ext_file[nm] != i) fail("routes: extension " nm " declared twice: " fname[ext_file[nm]] ", " fname[i])
    }
    if (stmt == "" && line !~ /\.Map[A-Za-z0-9_]*[(<]/) continue
    stmt = (stmt == "" ? line : stmt " " line)
    if (index(line, ";") > 0) { process(i, sc, stmt); stmt = "" }
  }
  if (rc < 0) fail("routes: cannot read " f)
  if (stmt != "") process(i, sc, stmt)
  close(f)
}
# prefix: the route prefix of variable v in scope sc, or the error marker "\001".
function prefix(sc, v, depth,   key, ext, pp) {
  if (depth > 40) return "\001"
  key = sc SUBSEP v
  if (key in gpar) { pp = prefix(sc, gpar[key], depth + 1); return (pp == "\001" ? pp : join(pp, gpath[key])) }
  ext = scope_ext[sc]
  # Only the top level of the host (Program.cs, where `app` lives) is the root; any other scope without an extension is unknown.
  if (ext == "") return (fkind[scope_file[sc]] == "P" ? "" : "\001")
  if (v == ext_param[ext] && (ext in caller_var)) return prefix(caller_scope[ext], caller_var[ext], depth + 1)
  return "\001"
}
function fail(msg) { print msg > errfile; failed = 1; exit 3 }
{
  sub(/\r$/, "")
  n = split($0, seg, "/")
  kind = ""
  if (n >= 6 && seg[1] == "src" && seg[2] == "Modules" && seg[n - 1] == "Endpoints" && seg[n] ~ /.Endpoints\.cs$/) kind = "E"
  else if (n == 5 && seg[1] == "src" && seg[2] == "Modules" && seg[5] ~ /.Module\.cs$/) kind = "M"
  else if (n == 4 && seg[1] == "src" && seg[2] == "Host" && seg[4] == "Program.cs") kind = "P"
  if (kind != "") { nf++; fname[nf] = $0; fkind[nf] = kind; fmod[nf] = seg[3] }
}
END {
  if (failed) exit 3
  for (i = 1; i <= nf; i++) scan_file(i)
  for (i = 1; i <= nf; i++) {
    if (fkind[i] != "E" || (i in routes)) continue
    if ((i in groups) || (i in unknown_at)) fail("no routes parsed in " fname[i] ((i in unknown_at) ? " (" unknown_at[i] ")" : ""))
  }
  for (i = 1; i <= nf; i++) if (i in unknown_at) fail("routes: unknown mapping shape in " fname[i] ": " unknown_at[i])
  for (r = 1; r <= nr; r++) {
    i = rfile[r]; arg = rarg[r]
    if (substr(arg, 1, 1) == "\"") arg = substr(arg, 2, length(arg) - 2)
    else {
      nm = arg; sub(/^.*\./, "", nm)
      if (!((i, nm) in konst)) fail("routes: the route constant " arg " is not a const string in " fname[i])
      arg = konst[i, nm]
    }
    p = prefix(rscope[r], rvar[r], 0)
    if (p == "\001") fail("routes: cannot resolve the group prefix of " rvar[r] " in " fname[i] " (an extension nothing calls, or a receiver the parser does not know)")
    route = join(p, arg)
    if (substr(route, 1, 1) != "/") route = "/" route
    if (rperm[r] == "-") fail("routes: no authorization call on " route " in " fname[i] " (RequirePermission, AllowAnonymous or RequireAuthorization on the route itself; group-level authorization is not read)")
    h = ((i, rmeth[r]) in handler) ? handler[i, rmeth[r]] : "-"
    row = fmod[i] "|" rverb[r] "|" route "|" h "|" rperm[r] "|" fname[i]
    print row
  }
}'

# emit_routes: the routes shard (see routes_awk); one awk process for the whole tree.
emit_routes() {
  local rows_file="$work/routes.awk.out" err_file="$work/routes.awk.err" status=0 msg="" lines=()
  : > "$err_file"
  awk -v errfile="$err_file" "$routes_awk" < "$files_cache" > "$rows_file" || status=$?
  if (( status != 0 )); then
    [[ -s "$err_file" ]] && read -r msg < "$err_file"
    fail_parse "${msg:-routes: awk failed (exit $status)}"
  fi
  mapfile -t lines < "$rows_file"
  if (( ${#lines[@]} > 0 )); then printf '%s\n' "${lines[@]}"; fi
}

# cs_awk_lib: awk functions shared by the permissions and errors parsers.
#   cs_read(f)    reads a C# file whole (CR removed) into two strings of the same length, so that a position in one is the same position
#                 in the other: RAW, the text with every // and /* */ comment blanked to spaces (newlines kept), and MASK, RAW with the
#                 contents of every string and char literal replaced by "_" (the quotes kept). Structure is matched on MASK, so that a
#                 parenthesis, a comma or a name inside a string or a comment is never read as code; values are taken from RAW at the same
#                 positions. Regular, verbatim (@"", with "" inside), raw ("""...""", over lines, closed by as many quotes as opened
#                 it) and interpolated strings are known; an interpolated string holding a quote inside a {hole} is not. Returns -1
#                 when the file cannot be read.
#   line_at(p)    the line number of position p of MASK.
#   fail(msg)     writes msg to errfile and exits 3 (the shell turns it into exit 2).
# shellcheck disable=SC2016
cs_awk_lib='
function cs_read(f,   line, rc, n, k, c, d, r, m, st, q, rq) {
  if (SQ == "") SQ = sprintf("%c", 39)
  RAW = ""; MASK = ""; st = 0
  while ((rc = (getline line < f)) > 0) {
    sub(/\r$/, "", line)
    n = length(line); r = ""; m = ""
    for (k = 1; k <= n; k++) {
      c = substr(line, k, 1); d = substr(line, k + 1, 1)
      if (st == 0) {
        if (c == "/" && d == "/") { for (; k <= n; k++) { r = r " "; m = m " " } break }
        if (c == "/" && d == "*") { r = r "  "; m = m "  "; k++; st = 4; continue }
        # Not after @ or @$: @"""x""..." and @$"""x""..." are verbatim strings that begin with an escaped quote.
        if (c == "\"" && substr(line, k, 3) == "\"\"\"" && substr(line, k - 1, 1) != "@" && substr(line, k - 2, 2) != "@$") {
          for (q = k; substr(line, q, 1) == "\""; q++) ;
          rq = substr(line, k, q - k); r = r rq; m = m rq; k = q - 1; st = 6; continue
        }
        if (c == "\"") st = (substr(line, k - 1, 1) == "@" || substr(line, k - 2, 2) == "@$") ? 2 : 1
        else if (c == SQ) st = 5
        r = r c; m = m c
      } else if (st == 1 || st == 5) {
        if (c == "\\") { r = r c d; m = m "__"; k++ }
        else if ((st == 1 && c == "\"") || (st == 5 && c == SQ)) { r = r c; m = m c; st = 0 }
        else { r = r c; m = m "_" }
      } else if (st == 2) {
        if (c == "\"" && d == "\"") { r = r c d; m = m "__"; k++ }
        else if (c == "\"") { r = r c; m = m c; st = 0 }
        else { r = r c; m = m "_" }
      } else if (st == 6) {
        if (c == "\"" && substr(line, k, length(rq)) == rq) { r = r rq; m = m rq; k += length(rq) - 1; st = 0 }
        else { r = r c; m = m "_" }
      } else {
        if (c == "*" && d == "/") { r = r "  "; m = m "  "; k++; st = 0 }
        else { r = r " "; m = m " " }
      }
    }
    # A regular string or a char literal ends at the end of its line; a verbatim string or a block comment may go on.
    if (st == 1 || st == 5) st = 0
    RAW = RAW r "\n"; MASK = MASK m "\n"
  }
  close(f)
  return (rc < 0 ? -1 : 0)
}
